-- Relatório 2 (junção): itens de compra com fornecedor e produto
SELECT COM.ID_COMPRA                          AS COMPRA
     , TO_CHAR(COM.DATA_COMPRA, 'DD/MM/YYYY') AS DATA
     , FORN.RAZAO_SOCIAL                      AS FORNECEDOR
     , PRO.NOME                               AS PRODUTO
     , ITE.QUANTIDADE                         AS QUANTIDADE
     , ITE.PRECO_UNITARIO                     AS PRECO_UNITARIO
     , ITE.QUANTIDADE * ITE.PRECO_UNITARIO    AS VALOR_ITEM
  FROM COMPRAS COM
 INNER JOIN FORNECEDORES FORN ON COM.ID_FORNECEDOR = FORN.ID_FORNECEDOR
 INNER JOIN ITENS_COMPRA ITE  ON COM.ID_COMPRA     = ITE.ID_COMPRA
 INNER JOIN PRODUTOS     PRO  ON ITE.ID_PRODUTO    = PRO.ID_PRODUTO
 ORDER BY COM.DATA_COMPRA, COM.ID_COMPRA, PRO.NOME

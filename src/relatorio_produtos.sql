-- Listagem usada antes de remover/atualizar produtos
SELECT PRO.ID_PRODUTO     AS CODIGO
     , PRO.NOME           AS PRODUTO
     , PRO.CATEGORIA      AS CATEGORIA
     , PRO.UNIDADE_MEDIDA AS UNIDADE
     , PRO.PRECO_CUSTO    AS PRECO_CUSTO
     , PRO.QTD_ESTOQUE    AS ESTOQUE
     , PRO.ESTOQUE_MINIMO AS MINIMO
     , FORN.RAZAO_SOCIAL  AS FORNECEDOR
  FROM PRODUTOS PRO
 INNER JOIN FORNECEDORES FORN ON PRO.ID_FORNECEDOR = FORN.ID_FORNECEDOR
 ORDER BY PRO.NOME

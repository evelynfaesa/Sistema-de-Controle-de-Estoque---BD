-- Relatório 1 (agrupamento): quantidade total comprada de cada produto
SELECT PRO.ID_PRODUTO                 AS CODIGO
     , PRO.NOME                       AS PRODUTO
     , PRO.UNIDADE_MEDIDA             AS UNIDADE
     , SUM(ITE.QUANTIDADE)            AS QUANTIDADE_COMPRADA
     , SUM(ITE.QUANTIDADE * ITE.PRECO_UNITARIO) AS VALOR_TOTAL
  FROM PRODUTOS PRO
 INNER JOIN ITENS_COMPRA ITE ON PRO.ID_PRODUTO = ITE.ID_PRODUTO
 GROUP BY PRO.ID_PRODUTO, PRO.NOME, PRO.UNIDADE_MEDIDA
 ORDER BY QUANTIDADE_COMPRADA DESC
